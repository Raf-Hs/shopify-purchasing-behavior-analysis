"""Render the data-quality report from the validation queries.

Run order: build_db.py -> run_queries.py -> make_quality_report.py

The report is generated rather than written by hand so that it can never drift
away from what the validation queries actually return.
"""

from __future__ import annotations

import sqlite3
from datetime import datetime, timezone

from analytics import default_params, load_query_library, run_query
from config import DB_PATH, DQ_SQL, QUALITY_REPORT_MD, QUALITY_REPORT_JSON
from run_queries import to_markdown

import json


def main() -> None:
    library = load_query_library()
    params = default_params()

    con = sqlite3.connect(DB_PATH)
    try:
        summary = run_query(con, "dq_summary", params, library)
        recon = run_query(con, "dq_row_reconciliation", params, library)
        statuses = run_query(con, "dq_status_distribution", params, library)
        variance = run_query(con, "dq_reconciliation_explained", params, library)
        defect_log = run_query(con, "dq_defect_log_summary", params, library)
        dq_file = DQ_SQL.read_text(encoding="utf-8").count("-- name:")
    finally:
        con.close()

    unexplained = 0
    if not variance.empty:
        unexplained = int((~variance["status"].str.startswith("Explained")).sum())

    total_flagged = int(summary["records_flagged"].sum())
    high_severity = int(summary[summary["severity"] == "high"]["records_flagged"].sum())

    lines = [
        "# Data quality report",
        "",
        "Generated by `src/make_quality_report.py` from "
        "`sql/05_data_quality.sql`. Every number below is the output of the",
        "named query beside it.",
        "",
        f"Built {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC} · database `{DB_PATH.name}` "
        f"· {dq_file} validation queries",
        "",
        "> The dataset is **synthetic**. The defects listed here were injected on",
        "> purpose by `src/generate_data.py` so that the cleaning rules have real",
        "> conditions to catch. In a real store the same checks would find whatever",
        "> that store actually gets wrong.",
        "",
        "## Headline",
        "",
        f"- **{total_flagged:,}** records flagged across all {len(summary)} checks.",
        f"- **{high_severity:,}** of them are high severity (they change a revenue or",
        "  order count if left unhandled).",
        f"- **{unexplained}** order-level reconciliation variances are unexplained.",
        "  Every variance is matched to an entry in the generator's defect log.",
        "",
        "## Checks",
        "",
        to_markdown(summary),
        "",
        "> A flagged count can be **lower** than the number of defects that were",
        "> injected, and that is a property of the check rather than a missed",
        "> defect. The `discount_amount` check is the clearest case: the generator",
        "> corrupts 12 discount values, but only the 3 that landed on a line with a",
        "> non-zero `discount_pct` and a positive quantity are detectable — halving a",
        "> zero discount still leaves zero. The test suite therefore asserts a",
        "> specific expected count per check rather than a single total.",
        "",
        "### How each defect is handled",
        "",
        "| Defect | Handling |",
        "|---|---|",
        "| Duplicate line item | De-duplicated on the Shopify business key "
        "`(order_id, product_id, quantity, unit_price, discount_pct)`; the row with the "
        "lowest `line_item_id` wins. A duplicate is a repeated export row, not a second sale. |",
        "| Orphan references (order / product / customer) | The row is dropped. An "
        "unattributable sale cannot be assigned revenue or a customer, so it is excluded "
        "rather than guessed at. |",
        "| Missing or non-positive quantity / unit price | The line is dropped. "
        "Revenue cannot be computed without them. |",
        "| Inconsistent `discount_amount` | Recomputed from `discount_pct`. The stored "
        "column is advisory; the percentage is authoritative. |",
        "| Order total that does not equal its components | The components are "
        "authoritative. The stored total is reported as a variance and nothing else "
        "depends on it. |",
        "| Completed order with no valid line items | Excluded from the eligible-order "
        "set. It has nothing to sell. |",
        "",
        "## Row counts through the pipeline",
        "",
        to_markdown(recon),
        "",
        "## Order status treatment",
        "",
        to_markdown(statuses),
        "",
        "## Reconciliation",
        "",
        "Each eligible order's stored subtotal is compared with the sum of its valid",
        "line items. The variances below are **all** explained by a line that the",
        "cleaning rules dropped or by a line that was detached from its order.",
        "",
        to_markdown(variance, max_rows=60),
        "",
        "## The defect log",
        "",
        "`src/generate_data.py` writes `data/raw/defects.csv` as it injects each defect.",
        "That log is loaded into the database so the build can assert that every",
        "reconciliation variance is accounted for.",
        "",
        to_markdown(defect_log),
        "",
    ]

    QUALITY_REPORT_MD.write_text("\n".join(lines), encoding="utf-8")

    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "records_flagged": total_flagged,
        "high_severity": high_severity,
        "unexplained_variances": unexplained,
        "checks": summary.to_dict(orient="records"),
        "row_reconciliation": recon.to_dict(orient="records"),
    }
    QUALITY_REPORT_JSON.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    print(f"wrote {QUALITY_REPORT_MD.name}")
    print(f"wrote {QUALITY_REPORT_JSON.name}")
    print(f"  records flagged : {total_flagged:,}")
    print(f"  high severity   : {high_severity:,}")
    print(f"  unexplained     : {unexplained}")


if __name__ == "__main__":
    main()
