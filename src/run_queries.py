"""Execute every named analysis query and write a readable results appendix.

Outputs:
    reports/sql_results.md   - every query, with its description and results
    reports/key_metrics.json - the headline KPIs, for the report and the tests

Run order: build_db.py -> run_queries.py -> make_figures.py
"""

from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timezone

import pandas as pd

from analytics import default_params, kpi_bundle, load_query_library, run_query
from config import (
    DB_PATH,
    KEY_METRICS_JSON,
    PERIOD_END,
    PERIOD_START,
    REPORTS_DIR,
    SQL_RESULTS_MD,
)


def _fmt(value, numeric: bool) -> str:
    """Format one cell.

    pandas' own markdown writer re-parses formatted numbers (turning
    "11,995,861" into scientific notation) and needs the optional `tabulate`
    package, so this small renderer keeps the output deterministic.
    """
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return ""
    if numeric:
        fv = float(value)
        if abs(fv) >= 1000 and fv.is_integer():
            return f"{fv:,.0f}"
        if abs(fv) >= 100:
            return f"{fv:,.1f}"
        return f"{fv:.4f}".rstrip("0").rstrip(".")
    return str(value).replace("|", "\\|")


def to_markdown(df: pd.DataFrame, max_rows: int = 200) -> str:
    """Render a DataFrame as a GitHub-flavoured markdown table."""
    if df.empty:
        return "_No rows returned._"

    frame = df.head(max_rows)
    headers = [str(c) for c in frame.columns]
    numeric = [bool(pd.api.types.is_numeric_dtype(frame[c])) for c in frame.columns]
    rows = [
        [_fmt(v, numeric[i]) for i, v in enumerate(rec)]
        for rec in frame.itertuples(index=False, name=None)
    ]

    widths = [max([len(h)] + [len(r[i]) for r in rows] + [3]) for i, h in enumerate(headers)]

    def render(cells: list[str]) -> str:
        padded = [
            cell.rjust(widths[i]) if numeric[i] else cell.ljust(widths[i])
            for i, cell in enumerate(cells)
        ]
        return "| " + " | ".join(padded) + " |"

    separator = (
        "|"
        + "|".join(
            ("-" * (w - 1) + ":") if numeric[i] else (":" + "-" * (w - 1))
            for i, w in enumerate(widths)
        )
        + "|"
    )

    lines = [render(headers), separator]
    lines.extend(render(row) for row in rows)
    if len(df) > max_rows:
        lines.append(f"\n_... {len(df) - max_rows:,} more rows not shown._")
    return "\n".join(lines)


def main() -> None:
    library = load_query_library()
    params = default_params()

    con = sqlite3.connect(DB_PATH)
    lines = [
        "# SQL analysis results",
        "",
        "Generated by `src/run_queries.py` from `sql/04_analysis_queries.sql` and",
        "`sql/05_data_quality.sql`. Every table below is the literal output of the",
        "named query beside it - nothing is hand-typed.",
        "",
        f"Database: `{DB_PATH.name}` · built {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}",
        f"Observation window: **{PERIOD_START} to {PERIOD_END}** (all eligible orders).",
        "Currency: USD. Shipping and tax are excluded from every revenue figure.",
        "",
        "Revenue definition: `quantity x unit_price x (1 - discount_pct)` per line,",
        "minus order refunds allocated pro-rata by net line value.",
        "",
        "> The dataset is **synthetic**. These numbers demonstrate the method; they",
        "> are not measurements of a real Shopify store.",
        "",
    ]

    try:
        for query in library.values():
            df = run_query(con, query.name, params, library)
            lines.append(f"## `{query.name}`")
            lines.append("")
            if query.description:
                lines.append(f"_{query.description}_")
                lines.append("")
            lines.append(to_markdown(df))
            lines.append("")
            print(f"{query.name:<38} {len(df):>4} rows")

        bundle = kpi_bundle(con, params, library)
    finally:
        con.close()

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    SQL_RESULTS_MD.write_text("\n".join(lines), encoding="utf-8")

    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "database": DB_PATH.name,
        "observation_window": {"start": PERIOD_START, "end": PERIOD_END},
        "currency": "USD",
        "data_origin": "synthetic",
        "kpis": {k: v for k, v in bundle.items() if k != "params"},
        "filters": bundle["params"],
    }
    KEY_METRICS_JSON.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    print(f"\nwrote {SQL_RESULTS_MD.name} ({len(library)} queries)")
    print(f"wrote {KEY_METRICS_JSON.name}")
    print()
    print("Headline KPIs")
    for key in (
        "total_net_revenue", "avg_order_value", "repeat_purchase_rate_pct",
        "eligible_orders", "units_sold", "unique_customers",
        "repeat_customers", "avg_orders_per_customer",
    ):
        print(f"  {key:<26} {bundle[key]:,}")


if __name__ == "__main__":
    main()
